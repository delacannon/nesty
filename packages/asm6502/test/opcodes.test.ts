describe('opcode encoding (hand-typed reference fixture)', () => {
  for (const [src, bytes] of FIXTURE) {
    it(src, () => {
      const r = assemble(src, { origin: 0x8000 });
      expect(r.errors).toEqual([]);
      expect(Array.from(r.bin)).toEqual(bytes);
    });
  }

  it('fixture covers 151 opcodes', () => {
    const seen = new Set<number>();
    for (const [src, bytes] of FIXTURE) {
      void src;
      seen.add(bytes[0]!);
    }
    expect(seen.size).toBe(151);
  });
});
