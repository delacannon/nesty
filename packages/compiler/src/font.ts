/** Ext-bank charset for a style: katakana bank or the accented latin set. */
export function fontExtChars(style: FontStyle = 'classic'): string {
  return style === 'katakana' ? KATAKANA_CHARS : FONT_EXT_CHARS;
}

/** Extended glyphs as CHR tiles, in fontExtChars(style) order. */
export function fontExtChrTiles(style: FontStyle = 'classic'): Uint8Array {
  if (style === 'katakana') {
    const out = new Uint8Array(KATAKANA_GLYPHS.length * 16);
    KATAKANA_GLYPHS.forEach((glyph, i) => out.set(glyphToChrTile(glyph), i * 16));
    return out;
  }
  const out = new Uint8Array(FONT_EXT_GLYPHS.length * 16);
  const src = style === 'thin' ? FONT_EXT_GLYPHS_THIN : FONT_EXT_GLYPHS;
  src.forEach((glyph, i) =>
    out.set(
      glyphToChrTile(style === 'thin' ? glyph : styleGlyph(glyph, style)),
      i * 16,
    ),
  );
  return out;
}
