// ---------------------------------------------------------- font styles ----
// Styles are generated from the base glyphs, so only the selected style is
// ever compiled into CHR. Base strokes are 2px thick.

type Grid = boolean[][];

function toGrid(rows: string[]): Grid {
  return Array.from({ length: 8 }, (_, y) =>
    Array.from({ length: 8 }, (_, x) => rows[y]?.[x] === '#'),
  );
}

function toRows(g: Grid): string[] {
  return g.map((row) => row.map((p) => (p ? '#' : '.')).join(''));
}

const at = (g: Grid, x: number, y: number): boolean =>
  x >= 0 && x < 8 && y >= 0 && y < 8 && g[y]![x]!;

/** Grow every stroke right+down: chunky 3px strokes. */
function bold(g: Grid): Grid {
  return g.map((row, y) =>
    row.map((p, x) => p || at(g, x - 1, y) || at(g, x, y - 1)),
  );
}

/** Clip outer corners of the 2px strokes: angular, techy. */
function scifi(g: Grid): Grid {
  return g.map((row, y) =>
    row.map((p, x) => {
      if (!p) return false;
      const l = at(g, x - 1, y);
      const r = at(g, x + 1, y);
      const u = at(g, x, y - 1);
      const d = at(g, x, y + 1);
      if ((l ? 1 : 0) + (r ? 1 : 0) !== 1 || (u ? 1 : 0) + (d ? 1 : 0) !== 1)
        return true;
      // L-corner; clip only when both strokes run at least 2px onward,
      // so small marks (periods, quotes) survive
      const dx = l ? -1 : 1;
      const dy = u ? -1 : 1;
      return !(at(g, x + 2 * dx, y) && at(g, x, y + 2 * dy));
    }),
  );
}

const shift = (g: Grid, dx: number, dy: number): Grid =>
  g.map((row, y) => row.map((_, x) => at(g, x - dx, y - dy)));

/**
 * Re-anchor a styled glyph to the classic glyph's bottom/left bbox edges,
 * like the original NES fonts: shared baseline, no per-style drift.
 */
function align(orig: Grid, out: Grid): Grid {
  const bottom = (g: Grid) => {
    for (let y = 7; y >= 0; y--) if (g[y]!.some(Boolean)) return y;
    return -1;
  };
  const left = (g: Grid) => {
    for (let x = 0; x < 8; x++) if (g.some((row) => row[x])) return x;
    return -1;
  };
  let res = out;
  const ob = bottom(orig);
  const nb = bottom(res);
  if (ob >= 0 && nb >= 0 && nb !== ob) res = shift(res, 0, ob - nb);
  const ol = left(orig);
  const nl = left(res);
  if (ol >= 0 && nl >= 0 && nl !== ol) res = shift(res, ol - nl, 0);
  return res;
}

function styleGlyph(rows: string[], style: FontStyle): string[] {
  // katakana style keeps the classic latin bank; kana live in the ext bank
  if (style === 'classic' || style === 'katakana') return rows;
  const g = toGrid(rows);
  const out = style === 'bold' ? bold(g) : scifi(g);
  return toRows(align(g, out));
}

/** All 64 glyphs as 64×16 bytes, in ASCII order from FONT_FIRST_CHAR. */
export function fontChrTiles(style: FontStyle = 'classic'): Uint8Array {
  const out = new Uint8Array(FONT_CHAR_COUNT * 16);
  const src = style === 'thin' ? FONT_GLYPHS_THIN : FONT_GLYPHS;
  src.forEach((glyph, i) =>
    out.set(
      glyphToChrTile(style === 'thin' ? glyph : styleGlyph(glyph, style)),
      i * 16,
    ),
  );
  return out;
}

