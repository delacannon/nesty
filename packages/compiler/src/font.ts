/** Pack one 8×8 glyph ('#' pixels, color 3) into 16 CHR bytes (2 bitplanes). */
export function glyphToChrTile(rows: string[]): Uint8Array {
  const tile = new Uint8Array(16);
  for (let y = 0; y < 8; y++) {
    let bits = 0;
    const row = rows[y] ?? '........';
    for (let x = 0; x < 8; x++) {
      if (row[x] === '#') bits |= 0x80 >> x;
    }
    tile[y] = 0xff; // plane 0: filled bg (color 1) so dialog box stays opaque
    tile[y + 8] = bits; // plane 1: glyph pixels become color 3
  }
  return tile;
}

